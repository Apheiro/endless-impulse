#!/usr/bin/env python3
"""Settings shortcut storage. stdout is a single JSON response for Quickshell."""
import ctypes
import ctypes.util
import fcntl
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile


CONFIG = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config")) / "artificial-impulse"
STATE = Path(os.environ.get("XDG_STATE_HOME", Path.home() / ".local/state")) / "artificial-impulse"
STORE = CONFIG / "shortcuts.lua"
HEADER = "-- Generated by Settings. Customize shortcuts through the Shortcuts page.\nreturn {\n"
MODIFIERS = ("SUPER", "CTRL", "ALT", "SHIFT", "MOD2", "MOD3", "MOD5")
ALIASES = {"CONTROL": "CTRL", "MOD4": "SUPER", "WIN": "SUPER"}


def normalize(value):
    parts = [p.strip() for p in value.split("+")]
    if not parts or any(not p for p in parts):
        raise ValueError("Enter a key combination, for example SUPER + SHIFT + E.")
    modifiers = [ALIASES.get(p.upper(), p.upper()) for p in parts[:-1]]
    if any(p not in MODIFIERS for p in modifiers) or len(set(modifiers)) != len(modifiers):
        raise ValueError("Use SUPER, CTRL, ALT, SHIFT, MOD2, MOD3 or MOD5 once each.")
    key = parts[-1]
    if re.fullmatch(r"(?:code|mouse):[1-9][0-9]*", key):
        pass
    elif key in ("mouse_up", "mouse_down", "mouse_left", "mouse_right", "catchall"):
        pass
    elif re.fullmatch(r"[A-Za-z0-9_]+", key):
        library = os.environ.get("DOTS_XKBCOMMON_LIBRARY") or ctypes.util.find_library("xkbcommon") or "libxkbcommon.so.0"
        xkb = ctypes.CDLL(library)
        xkb.xkb_keysym_from_name.argtypes = [ctypes.c_char_p, ctypes.c_int]
        xkb.xkb_keysym_from_name.restype = ctypes.c_uint32
        if not xkb.xkb_keysym_from_name(key.encode(), 1):
            raise ValueError(f"Unknown key: {key}. Use a keysym such as Return, F1 or XF86AudioMute.")
    else:
        raise ValueError("Invalid key. Use a keysym, code:NUMBER or mouse:NUMBER.")
    return " + ".join([m for m in MODIFIERS if m in modifiers] + [key])


def signature(value):
    return "+".join(sorted(ALIASES.get(p.strip().upper(), p.strip().upper()) for p in value.split("+")[:-1])
                    + [value.split("+")[-1].strip().upper()])


def read_overrides():
    if not STORE.exists():
        return {}
    text = STORE.read_text()
    if not text.startswith(HEADER) or not text.endswith("}\n"):
        raise ValueError("Shortcut storage was edited externally; refusing to overwrite it.")
    result = {}
    string = r'"(?:[^"\\]|\\.)*"'
    for line in text[len(HEADER):-2].splitlines():
        match = re.fullmatch(r"\s*\[(" + string + r")\] = (" + string + r"),", line)
        if not match:
            raise ValueError("Invalid shortcut storage; refusing to overwrite it.")
        result[json.loads(match[1])] = json.loads(match[2])
    return result


def catalog():
    path = STATE / "shortcuts-catalog.json"
    if not path.exists():
        raise ValueError("Shortcut editing requires this project's updated Hyprland configuration. "
                         "Running only the Quickshell interface does not enable it. "
                         "Load the updated Hyprland configuration in your test session first.")
    return json.loads(path.read_text())


def atomic_write(content):
    with tempfile.NamedTemporaryFile(mode="w", dir=CONFIG, delete=False) as file:
        temporary = Path(file.name)
        try:
            file.write(content)
            file.flush()
            os.fsync(file.fileno())
        except BaseException:
            temporary.unlink(missing_ok=True)
            raise
    temporary.replace(STORE)


def save(overrides):
    encode = lambda value: json.dumps(value, ensure_ascii=False)
    atomic_write(HEADER + "".join(f"    [{encode(k)}] = {encode(v)},\n"
                                 for k, v in sorted(overrides.items())) + "}\n")


def run_hyprctl(*args):
    result = subprocess.run(["hyprctl", *args], capture_output=True, text=True, timeout=10)
    if result.returncode:
        raise ValueError(result.stderr.strip() or result.stdout.strip() or "Hyprland is unavailable.")
    return result.stdout.strip()


def rows(entries, overrides):
    return [dict(entry, current=overrides.get(entry["id"], entry["default"]),
                 modified=entry["id"] in overrides) for entry in entries]


def update(action, identifier, value, entries, overrides):
    selected = next((e for e in entries if e["id"] == identifier), None)
    if selected is None:
        raise ValueError("This shortcut no longer exists. Refresh the list.")
    target = normalize(value) if action == "set" else selected["default"]
    for entry in entries:
        if entry["id"] == identifier:
            continue
        if entry["submap"] != selected["submap"] and not (entry.get("universal") or selected.get("universal")):
            continue
        existing = signature(overrides.get(entry["id"], entry["default"]))
        requested = signature(target)
        # Defaults intentionally overlap (e.g. Super press/release with ignore_mods).
        if requested == signature(selected["default"]) and existing == signature(entry["default"]):
            continue
        same_key = existing.split("+")[-1] == requested.split("+")[-1]
        if existing == requested or (same_key and (entry.get("ignore_mods") or selected.get("ignore_mods"))):
            raise ValueError("Shortcut already used by " + (entry["description"] or entry["default"]) + ".")
    if signature(target) == signature(selected["default"]):
        overrides.pop(identifier, None)
    else:
        overrides[identifier] = target
    previous = STORE.read_text() if STORE.exists() else None
    save(overrides)
    try:
        run_hyprctl("reload")
        errors = run_hyprctl("configerrors")
        if errors:
            raise ValueError(errors)
    except (ValueError, subprocess.TimeoutExpired) as error:
        if previous is None:
            STORE.unlink(missing_ok=True)
        else:
            atomic_write(previous)
        try:
            run_hyprctl("reload")
        except (ValueError, subprocess.TimeoutExpired):
            pass
        raise ValueError(f"Could not apply shortcut; saved changes were rolled back: {error}") from error


def main():
    action = sys.argv[1] if len(sys.argv) > 1 else "list"
    if action not in ("list", "set", "reset"):
        raise ValueError("Unknown shortcut action.")
    CONFIG.mkdir(parents=True, exist_ok=True)
    with (CONFIG / "shortcuts.lock").open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        entries, overrides = catalog(), read_overrides()
        if action != "list":
            if len(sys.argv) != (4 if action == "set" else 3):
                raise ValueError("Missing shortcut arguments.")
            update(action, sys.argv[2], sys.argv[3] if action == "set" else "", entries, overrides)
        return {"ok": True, "shortcuts": rows(entries, overrides)}


if __name__ == "__main__":
    try:
        response = main()
    except (ValueError, OSError, subprocess.TimeoutExpired) as error:
        response = {"ok": False, "error": str(error)}
    print(json.dumps(response))
    sys.exit(0 if response["ok"] else 1)
